-- 用户关系服务初始化建表脚本。
-- 每个发起关系操作的用户一行，用事务行锁保护关注上限，不存储异步计数。
CREATE TABLE t_relation_user_lock (
 user_id BIGINT NOT NULL PRIMARY KEY
) ENGINE=InnoDB;
CREATE TABLE t_following (
 id BIGINT NOT NULL AUTO_INCREMENT, from_user_id BIGINT NOT NULL, to_user_id BIGINT NOT NULL,
 type TINYINT NOT NULL, version BIGINT NOT NULL DEFAULT 1, update_time DATETIME(3) NOT NULL,
 PRIMARY KEY(id), UNIQUE KEY uk_relation(from_user_id,to_user_id),
 KEY idx_following(from_user_id,to_user_id,type), KEY idx_following_list(from_user_id,type,update_time,to_user_id)
) ENGINE=InnoDB;
CREATE TABLE t_follower (
 id BIGINT NOT NULL, from_user_id BIGINT NOT NULL, to_user_id BIGINT NOT NULL,
 type TINYINT NOT NULL, version BIGINT NOT NULL DEFAULT 1, update_time DATETIME(3) NOT NULL,
 PRIMARY KEY(id), UNIQUE KEY uk_relation(to_user_id,from_user_id),
 KEY idx_follower(to_user_id,from_user_id,type), KEY idx_follower_list(to_user_id,type,update_time,from_user_id)
) ENGINE=InnoDB;
-- Event ID generated by this database; allocated inside the source transaction.
CREATE TABLE t_relation_outbox (
 event_id BIGINT NOT NULL AUTO_INCREMENT, relation_id BIGINT NOT NULL, relation_version BIGINT NOT NULL,
 payload JSON NOT NULL, status TINYINT NOT NULL DEFAULT 0,
 retry_count INT NOT NULL DEFAULT 0, next_retry_time DATETIME(3) NOT NULL,
 lease_until DATETIME(3), claim_token VARCHAR(64), create_time DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 sent_time DATETIME(3), last_error VARCHAR(500), PRIMARY KEY(event_id),
 KEY idx_pending(status,next_retry_time), KEY idx_lease(status,lease_until),
 UNIQUE KEY uk_relation_version(relation_id,relation_version)
) ENGINE=InnoDB;
